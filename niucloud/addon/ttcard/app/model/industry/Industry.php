namespace addon\ttcard\app\model\industry;

use core\base\BaseModel;
use think\model\concern\SoftDelete;
use think\model\relation\HasMany;
use think\model\relation\HasOne;

/**
 * 行业管理模型
 * Class Industry
 * @package addon\ttcard\app\model\industry
 */
class Industry extends BaseModel
{

    

    /**
     * 数据表主键
     * @var string
     */
    protected $pk = 'id';

    /**
     * 模型名称
     * @var string
     */
    protected $name = 'ttcard_industry';

    

    

    /**
     * 搜索器:行业管理名称
     * @param $value
     * @param $data
     */
    public function searchNameAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("name", $value);
        }
    }
    
    /**
     * 搜索器:行业管理标志
     * @param $value
     * @param $data
     */
    public function searchFlagStatusAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("flag_status", $value);
        }
    }
    
    /**
     * 搜索器:行业管理状态
     * @param $value
     * @param $data
     */
    public function searchStatusAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("status", $value);
        }
    }
    
    

    

    
}

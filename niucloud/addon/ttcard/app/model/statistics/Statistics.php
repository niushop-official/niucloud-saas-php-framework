namespace addon\ttcard\app\model\statistics;

use core\base\BaseModel;
use think\model\concern\SoftDelete;
use think\model\relation\HasMany;
use think\model\relation\HasOne;

use addon\ttcard\app\model\user\User;

use addon\ttcard\app\model\card\Card;

/**
 * 数据统计管理模型
 * Class Statistics
 * @package addon\ttcard\app\model\statistics
 */
class Statistics extends BaseModel
{

    

    /**
     * 数据表主键
     * @var string
     */
    protected $pk = 'id';

    /**
     * 模型名称
     * @var string
     */
    protected $name = 'ttcard_statistics';

    

    

    /**
     * 搜索器:数据统计管理事件
     * @param $value
     * @param $data
     */
    public function searchTypeAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("type", $value);
        }
    }
    
    /**
     * 搜索器:数据统计管理来自用户ID
     * @param $value
     * @param $data
     */
    public function searchFromUserIdAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("from_user_id", $value);
        }
    }
    
    /**
     * 搜索器:数据统计管理名片用户ID
     * @param $value
     * @param $data
     */
    public function searchUserIdAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("user_id", $value);
        }
    }
    
    /**
     * 搜索器:数据统计管理名片ID
     * @param $value
     * @param $data
     */
    public function searchCardIdAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("card_id", $value);
        }
    }
    
    /**
     * 搜索器:数据统计管理IP
     * @param $value
     * @param $data
     */
    public function searchIpAttr($query, $value, $data)
    {
       if ($value) {
            $query->where("ip", $value);
        }
    }
    
    /**
     * 搜索器:数据统计管理创建时间
     * @param $value
     * @param $data
     */
    public function searchCreateTimeAttr($query, $value, $data)
    {
        $start = empty($value[0]) ? 0 : strtotime($value[0]);
        $end = empty($value[1]) ? 0 : strtotime($value[1]);
        if ($start > 0 && $end > 0) {
             $query->where([["create_time", "between", [$start, $end]]]);
        } else if ($start > 0 && $end == 0) {
            $query->where([["create_time", ">=", $start]]);
        } else if ($start == 0 && $end > 0) {
            $query->where([["create_time", "<=", $end]]);
        }
    }
    
    

    

    
    public function user(){
       return $this->hasOne(User::class, 'id', 'from_user_id')->joinType('left')->withField('nickname,id')->bind(['from_user_id_name'=>'nickname']);
    }

    public function user2(){
       return $this->hasOne(User::class, 'id', 'user_id')->joinType('left')->withField('nickname,id')->bind(['user_id_name'=>'nickname']);
    }

    public function card(){
       return $this->hasOne(Card::class, 'id', 'card_id')->joinType('left')->withField('name,id')->bind(['card_id_name'=>'name']);
    }

}
